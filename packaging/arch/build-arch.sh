#!/usr/bin/env bash
# packaging/arch/build-arch.sh — Generador automatizado de paquetes nativos .pkg.tar.zst para Arch Linux
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
VERSION="$(grep -E '^version\s*=' "${REPO_DIR}/Cargo.toml" | head -n1 | sed -E 's/^version\s*=\s*"([^"]+)".*/\1/')"
OUTPUT_DIR="${REPO_DIR}/dist"
STAGE_DIR="${REPO_DIR}/packaging/arch/stage"
PKG_FILE="${OUTPUT_DIR}/criperto-notes-${VERSION}-1-x86_64.pkg.tar.zst"

mkdir -p "${OUTPUT_DIR}"
rm -rf "${STAGE_DIR}"
mkdir -p "${STAGE_DIR}"

echo "==> Preparando estructura de paquete Arch Linux para Notas v${VERSION}..."
PREFIX="/usr" DESTDIR="${STAGE_DIR}" bash "${REPO_DIR}/scripts/install.sh" --system >/dev/null 2>&1

INSTALLED_SIZE=$(du -sb "${STAGE_DIR}" 2>/dev/null | cut -f1 || true)
if [[ -z "${INSTALLED_SIZE}" ]]; then
    INSTALLED_SIZE=$(du -sk "${STAGE_DIR}" | awk '{print $1 * 1024}')
fi
BUILD_DATE=$(date +%s)

cat << EOF > "${STAGE_DIR}/.PKGINFO"
# Generated by criperto-notes arch packaging
pkgname = criperto-notes
pkgbase = criperto-notes
xdata = pkgtype=pkg
pkgver = ${VERSION}-1
pkgdesc = Editor moderno y nativo de notas en Markdown para Wayland
url = https://github.com/Criperto/notes
builddate = ${BUILD_DATE}
packager = Tomas (Criperto) <dev@criperto.com>
size = ${INSTALLED_SIZE}
arch = x86_64
license = GPL-3.0-or-later
depend = qt6-base
depend = qt6-declarative
depend = qt6-svg
depend = gcc-libs
depend = glibc
optdepend = qt6-wayland: soporte nativo Wayland
optdepend = wl-clipboard: integración avanzada de portapapeles en Wayland
provides = notas
conflict = notas
EOF

echo "==> Comprimiendo paquete en ${PKG_FILE}..."
if command -v zstd &>/dev/null; then
    (cd "${STAGE_DIR}" && tar --numeric-owner --owner=0 --group=0 -cf - .PKGINFO usr | zstd -c -T0 -19 > "${PKG_FILE}")
elif command -v bsdtar &>/dev/null; then
    (cd "${STAGE_DIR}" && bsdtar --zstd -cf "${PKG_FILE}" .PKGINFO usr)
else
    echo "❌ Error: Ni zstd ni bsdtar están disponibles para comprimir el paquete Arch." >&2
    exit 1
fi

(cd "${OUTPUT_DIR}" && sha256sum "$(basename "${PKG_FILE}")" > "$(basename "${PKG_FILE}").sha256")
echo "✓ Paquete Arch Linux generado con éxito en ${PKG_FILE}"

if command -v pacman &>/dev/null; then
    echo "==> Verificando metadatos del paquete con pacman..."
    pacman -Qip "${PKG_FILE}" | head -n 12
    echo "✓ Verificación con pacman superada."
fi

rm -rf "${STAGE_DIR}"
